// A seeded random source (mulberry32): the same seed always deals the same game, which
// is what makes staged screenshots and headless play tests reproducible. Everything in
// the simulation draws from this one stream; nothing in it touches Math.random.

/** Create a generator from a 32-bit seed. */
export function createRandom(seed) {
  let state = seed >>> 0;
  /** The next float in [0, 1). */
  function next() {
    state = (state + 0x6d2b79f5) >>> 0;
    let t = state;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  }
  return {
    next,
    /** A float in [min, max). */
    range(min, max) {
      return min + next() * (max - min);
    },
    /** An integer in [min, max], both ends included. */
    int(min, max) {
      return min + Math.floor(next() * (max - min + 1));
    },
    /** One element of a non-empty array. */
    pick(items) {
      return items[Math.floor(next() * items.length)];
    },
    /** True with probability p. */
    chance(p) {
      return next() < p;
    },
  };
}
